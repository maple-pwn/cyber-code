export type TranslationKey = DictionaryKey;
export type TranslationVariables = Readonly<Record<string, string | number>>;
export type Translator = {
  locale: Locale;
  t: (key: TranslationKey, variables?: TranslationVariables) => string;
};

let activeLocale: Locale = 'zh-CN';

export function setLocale(locale: Locale): void {
  activeLocale = locale;
}

export function getLocale(): Locale {
  return activeLocale;
}

export function createTranslator(locale: Locale = activeLocale): Translator {
  return {
    locale,
    t(key, variables = {}) {
      return Object.entries(variables).reduce(
        (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
        DICTIONARIES[locale][key] as string,
      );
    },
  };
}
